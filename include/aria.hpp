inline constexpr block_t c2 = {0x6d, 0xb1, 0x4a, 0xcc, 0x9e, 0x21, 0xc8, 0x20,
                               0xff, 0x28, 0xb1, 0xd5, 0xef, 0x5d, 0xe2, 0xb0};
inline constexpr block_t c3 = {0xdb, 0x92, 0x37, 0x1d, 0x21, 0x26, 0xe9, 0x70,
                               0x03, 0x24, 0x97, 0x75, 0x04, 0xe8, 0xc9, 0x0e};

class cipher
{
  public:
    using block_t = ::aria::block_t;
    static constexpr std::size_t block_len = ::aria::block_len;

  private:
    // 17 round keys is the widest ARIA has.
    block_t ek_[17] = {};
    std::size_t rounds_ = 0;

  public:
    cipher(const std::uint8_t *key, std::size_t key_len) noexcept
    {
        rounds_ = key_len == 16 ? 12 : key_len == 24 ? 14 : 16;

        block_t kl{};
        block_t kr{};
        std::copy(key, key + 16, kl.begin());
        if (key_len > 16)
            std::copy(key + 16, key + key_len, kr.begin());

        // CK1, CK2, CK3 depend on the key size (section 2.2).
        const block_t *ck1 = &c1;
        const block_t *ck2 = &c2;
        const block_t *ck3 = &c3;
        if (key_len == 24)
        {
            ck1 = &c2;
            ck2 = &c3;
            ck3 = &c1;
        }
        else if (key_len == 32)
        {
            ck1 = &c3;
            ck2 = &c1;
            ck3 = &c2;
        }

        // W0..W3: three rounds of a 256-bit Feistel network over KL || KR.
        const block_t w0 = kl;
        const block_t w1 = xor_block(fo(w0, *ck1), kr);
        const block_t w2 = xor_block(fe(w1, *ck2), w0);
        const block_t w3 = xor_block(fo(w2, *ck3), w1);

        const u128 a = to_u128(w0), b = to_u128(w1), c = to_u128(w2),
                   d = to_u128(w3);
        block_t keys[17];
        keys[0] = from_u128(xr(a, ror(b, 19)));
        keys[1] = from_u128(xr(b, ror(c, 19)));
        keys[2] = from_u128(xr(c, ror(d, 19)));
        keys[3] = from_u128(xr(ror(a, 19), d));
        keys[4] = from_u128(xr(a, ror(b, 31)));
        keys[5] = from_u128(xr(b, ror(c, 31)));
        keys[6] = from_u128(xr(c, ror(d, 31)));
        keys[7] = from_u128(xr(ror(a, 31), d));
        keys[8] = from_u128(xr(a, rol(b, 61)));
        keys[9] = from_u128(xr(b, rol(c, 61)));
        keys[10] = from_u128(xr(c, rol(d, 61)));
        keys[11] = from_u128(xr(rol(a, 61), d));
        keys[12] = from_u128(xr(a, rol(b, 31)));
        keys[13] = from_u128(xr(b, rol(c, 31)));
        keys[14] = from_u128(xr(c, rol(d, 31)));
        keys[15] = from_u128(xr(rol(a, 31), d));
        keys[16] = from_u128(xr(a, rol(b, 19)));
        std::copy(keys, keys + 17, ek_);
    }

    block_t encrypt(const block_t &in) const noexcept
    {
        block_t p = in;
        for (std::size_t r = 0; r + 1 < rounds_; ++r)
            p = (r % 2 == 0) ? fo(p, ek_[r]) : fe(p, ek_[r]);
        p = sl2(xor_block(p, ek_[rounds_ - 1]));
        return xor_block(p, ek_[rounds_]);
    }
};
