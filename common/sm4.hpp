inline std::uint32_t tau(std::uint32_t x) noexcept
{
    return static_cast<std::uint32_t>(sbox[(x >> 24) & 0xff]) << 24 |
           static_cast<std::uint32_t>(sbox[(x >> 16) & 0xff]) << 16 |
           static_cast<std::uint32_t>(sbox[(x >> 8) & 0xff]) << 8 |
           static_cast<std::uint32_t>(sbox[x & 0xff]);
}

inline std::uint32_t t(std::uint32_t x) noexcept
{
    const std::uint32_t b = tau(x);
    return b ^ rol(b, 2) ^ rol(b, 10) ^ rol(b, 18) ^ rol(b, 24);
}

inline std::uint32_t t_prime(std::uint32_t x) noexcept
{
    const std::uint32_t b = tau(x);
    return b ^ rol(b, 13) ^ rol(b, 23);
}

class cipher
{
  private:
    std::uint32_t rk_[32] = {};

  public:
    using block_t = ::sm4::block_t;
    static constexpr std::size_t block_len = ::sm4::block_len;

    cipher(const std::uint8_t *key,
           [[maybe_unused]] std::size_t key_len) noexcept
    {
        std::uint32_t k[4];
        for (std::size_t i = 0; i < 4; ++i)
        {
            const std::size_t at = 4 * i;
            k[i] = (static_cast<std::uint32_t>(key[at]) << 24 |
                    static_cast<std::uint32_t>(key[at + 1]) << 16 |
                    static_cast<std::uint32_t>(key[at + 2]) << 8 |
                    static_cast<std::uint32_t>(key[at + 3])) ^
                   fk[i];
        }
        for (std::size_t i = 0; i < 32; ++i)
        {
            rk_[i] = k[0] ^ t_prime(k[1] ^ k[2] ^ k[3] ^ ck[i]);
            k[0] = k[1];
            k[1] = k[2];
            k[2] = k[3];
            k[3] = rk_[i];
        }
    }

    block_t encrypt(const block_t &in) const noexcept
    {
        std::uint32_t x[4];
        for (std::size_t i = 0; i < 4; ++i)
            x[i] = static_cast<std::uint32_t>(in[4 * i]) << 24 |
                   static_cast<std::uint32_t>(in[4 * i + 1]) << 16 |
                   static_cast<std::uint32_t>(in[4 * i + 2]) << 8 |
                   static_cast<std::uint32_t>(in[4 * i + 3]);

        for (std::size_t i = 0; i < 32; ++i)
        {
            const std::uint32_t next = x[0] ^ t(x[1] ^ x[2] ^ x[3] ^ rk_[i]);
            x[0] = x[1];
            x[1] = x[2];
            x[2] = x[3];
            x[3] = next;
        }

        block_t out{};
        for (std::size_t i = 0; i < 4; ++i)
        {
            const std::uint32_t v = x[3 - i];
            out[4 * i] = static_cast<std::uint8_t>(v >> 24);
            out[4 * i + 1] = static_cast<std::uint8_t>(v >> 16);
            out[4 * i + 2] = static_cast<std::uint8_t>(v >> 8);
            out[4 * i + 3] = static_cast<std::uint8_t>(v);
        }
        return out;
    }
};

