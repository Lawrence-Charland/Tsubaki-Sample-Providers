class cipher
{
  private:
    std::uint32_t k_[32] = {};

    // F: the three-layer G construction from RFC 4269 section 2.1.
    static std::uint64_t f(std::uint64_t r, std::uint32_t k0,
                           std::uint32_t k1) noexcept
    {
        const std::uint32_t t0 = static_cast<std::uint32_t>(r >> 32) ^ k0;
        const std::uint32_t t1 = static_cast<std::uint32_t>(r) ^ k1;
        const std::uint32_t a = g(t0 ^ t1);
        const std::uint32_t b = g(a + t0);
        const std::uint32_t c = g(b + a);
        return (static_cast<std::uint64_t>(c + b) << 32) | c;
    }

  public:
    static constexpr std::size_t block_len = ::seed::block_len;
    using block_t = ::seed::block_t;

    cipher(const std::uint8_t *key,
           [[maybe_unused]] std::size_t key_len) noexcept
    {
        std::uint32_t key0 = be32(key);
        std::uint32_t key1 = be32(key + 4);
        std::uint32_t key2 = be32(key + 8);
        std::uint32_t key3 = be32(key + 12);

        for (std::size_t i = 0; i < 16; ++i)
        {
            k_[2 * i] = g(key0 + key2 - kc[i]);
            k_[2 * i + 1] = g(key1 - key3 + kc[i]);
            if (i % 2 == 0)
            {
                // Odd round: rotate Key0 || Key1 right by 8 bits.
                const std::uint32_t t = key0;
                key0 = (key0 >> 8) | (key1 << 24);
                key1 = (key1 >> 8) | (t << 24);
            }
            else
            {
                // Even round: rotate Key2 || Key3 left by 8 bits.
                const std::uint32_t t = key2;
                key2 = (key2 << 8) | (key3 >> 24);
                key3 = (key3 << 8) | (t >> 24);
            }
        }
    }

    block_t encrypt(const block_t &in) const noexcept
    {
        std::uint64_t l = (static_cast<std::uint64_t>(be32(in.data())) << 32) |
                          be32(in.data() + 4);
        std::uint64_t r = (static_cast<std::uint64_t>(be32(in.data() + 8)) << 32) |
                          be32(in.data() + 12);

        for (std::size_t i = 0; i < 15; ++i)
        {
            const std::uint64_t t = r;
            r = l ^ f(r, k_[2 * i], k_[2 * i + 1]);
            l = t;
        }
        l ^= f(r, k_[30], k_[31]);

        block_t out{};
        put_be32(out.data(), static_cast<std::uint32_t>(l >> 32));
        put_be32(out.data() + 4, static_cast<std::uint32_t>(l));
        put_be32(out.data() + 8, static_cast<std::uint32_t>(r >> 32));
        put_be32(out.data() + 12, static_cast<std::uint32_t>(r));
        return out;
    }
};
