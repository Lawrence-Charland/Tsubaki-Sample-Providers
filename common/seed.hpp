// The masks from RFC 4269 section 2.2.
inline constexpr std::uint8_t m0 = 0xfc, m1 = 0xf3, m2 = 0xcf, m3 = 0x3f;

struct ss_boxes
{
    std::uint32_t v[4][256];
};

// SS0..SS3 as the byte permutations of S0/S1 that the RFC spells out.
consteval ss_boxes make_ss_boxes() noexcept
{
    ss_boxes t{};
    for (std::size_t i = 0; i < 256; ++i)
    {
        const std::uint32_t a = s0[i];
        const std::uint32_t b = s1[i];
        t.v[0][i] = ((a & m3) << 24) | ((a & m2) << 16) | ((a & m1) << 8) |
                    (a & m0);
        t.v[1][i] = ((b & m0) << 24) | ((b & m3) << 16) | ((b & m2) << 8) |
                    (b & m1);
        t.v[2][i] = ((a & m1) << 24) | ((a & m0) << 16) | ((a & m3) << 8) |
                    (a & m2);
        t.v[3][i] = ((b & m2) << 24) | ((b & m1) << 16) | ((b & m0) << 8) |
                    (b & m3);
    }
    return t;
}

inline constexpr ss_boxes ss = make_ss_boxes();

inline std::uint32_t g(std::uint32_t x) noexcept
{
    // X0 is the least significant byte: Z = SS0(X0) ^ SS1(X1) ^ SS2(X2) ^
    // SS3(X3), so the index runs from the low end.
    return ss.v[0][x & 0xff] ^ ss.v[1][(x >> 8) & 0xff] ^
           ss.v[2][(x >> 16) & 0xff] ^ ss.v[3][x >> 24];
}

inline std::uint32_t be32(const std::uint8_t *p) noexcept
{
    return static_cast<std::uint32_t>(p[0]) << 24 |
           static_cast<std::uint32_t>(p[1]) << 16 |
           static_cast<std::uint32_t>(p[2]) << 8 |
           static_cast<std::uint32_t>(p[3]);
}

inline void put_be32(std::uint8_t *p, std::uint32_t v) noexcept
{
    p[0] = static_cast<std::uint8_t>(v >> 24);
    p[1] = static_cast<std::uint8_t>(v >> 16);
    p[2] = static_cast<std::uint8_t>(v >> 8);
    p[3] = static_cast<std::uint8_t>(v);
}

